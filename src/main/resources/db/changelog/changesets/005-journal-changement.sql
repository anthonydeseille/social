--comment Journal des changements détectés sur les articles entre deux ingestions (traçabilité : exécution batch + révision git du dump).
CREATE TABLE journal_changement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_source_id VARCHAR(64) NOT NULL,
    cid VARCHAR(64),
    texte_id BIGINT NOT NULL,
    type_changement VARCHAR(32) NOT NULL,
    etat_avant VARCHAR(32),
    etat_apres VARCHAR(32),
    hash_avant VARCHAR(64),
    hash_apres VARCHAR(64),
    detecte_le TIMESTAMP WITH TIME ZONE NOT NULL,
    execution_id BIGINT,
    revision_source VARCHAR(64),
    CONSTRAINT journal_texte_fk FOREIGN KEY (texte_id) REFERENCES texte (id)
);

CREATE INDEX idx_journal_article ON journal_changement (article_source_id);
CREATE INDEX idx_journal_execution ON journal_changement (execution_id);

