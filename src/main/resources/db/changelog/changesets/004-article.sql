--comment Article versionné (LEGIARTI / KALIARTI). source_id = identité de version (clé d'upsert), cid = identité stable regroupant les versions.
CREATE TABLE article (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id VARCHAR(64) NOT NULL,
    cid VARCHAR(64),
    texte_id BIGINT NOT NULL,
    section_id BIGINT,
    num VARCHAR(128),
    etat VARCHAR(32),
    date_debut DATE,
    date_fin DATE,
    int_ordre INTEGER,
    contenu_texte TEXT,
    contenu_html TEXT,
    nota TEXT,
    contenu_hash VARCHAR(64) NOT NULL,
    donnees_brutes JSONB,
    ingere_le TIMESTAMP WITH TIME ZONE NOT NULL,
    maj_le TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT article_source_id_un UNIQUE (source_id),
    CONSTRAINT article_texte_fk FOREIGN KEY (texte_id) REFERENCES texte (id),
    CONSTRAINT article_section_fk FOREIGN KEY (section_id) REFERENCES section (id)
);

CREATE INDEX idx_article_cid ON article (cid);
CREATE INDEX idx_article_num ON article (num);
CREATE INDEX idx_article_texte ON article (texte_id);

