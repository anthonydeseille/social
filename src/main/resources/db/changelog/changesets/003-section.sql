--comment Section de la hiérarchie unist (LEGISCTA / KALISCTA), rattachée à un texte et éventuellement à une section parente.
CREATE TABLE section (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id VARCHAR(64) NOT NULL,
    cid VARCHAR(64),
    texte_id BIGINT NOT NULL,
    parent_id BIGINT,
    titre TEXT,
    etat VARCHAR(32),
    int_ordre INTEGER,
    date_debut DATE,
    date_fin DATE,
    CONSTRAINT section_source_id_un UNIQUE (source_id),
    CONSTRAINT section_texte_fk FOREIGN KEY (texte_id) REFERENCES texte (id),
    CONSTRAINT section_parent_fk FOREIGN KEY (parent_id) REFERENCES section (id)
);

CREATE INDEX idx_section_texte ON section (texte_id);
CREATE INDEX idx_section_parent ON section (parent_id);

